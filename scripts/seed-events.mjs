async function main() {
  console.log("── Seed دسته‌بندی‌ها ──");
  for (const c of CATEGORIES) {
    await prisma.category.upsert({
      where: { slug: c.slug },
      update: { title: c.title, sortOrder: c.sortOrder, isActive: true },
      create: c,
    });
    console.log(`  ✓ ${c.title} (${c.slug})`);
  }

  console.log("── Seed ایونت‌ها ──");
  for (const e of EVENTS) {
    const { categorySlug, ...data } = e;
    const payload = {
      ...data,
      status: "PUBLISHED",
      waitlistEnabled: true,
      category: { connect: { slug: categorySlug } },
    };
    await prisma.event.upsert({
      where: { slug: e.slug },
      update: {
        title: e.title,
        summary: e.summary,
        description: e.description,
        coverImage: e.coverImage,
        startsAt: new Date(e.startsAt),
        endsAt: e.endsAt ? new Date(e.endsAt) : null,
        venueName: e.venueName,
        venueAddress: e.venueAddress,
        venueCity: e.venueCity,
        capacity: e.capacity,
        isFeatured: e.isFeatured,
        status: "PUBLISHED",
        metaTitle: e.metaTitle,
        metaDescription: e.metaDescription,
        categoryId: undefined,
      },
      create: payload,
    });
    console.log(`  ✓ ${e.title}`);
  }

  const counts = {
    categories: await prisma.category.count(),
    events: await prisma.event.count(),
  };
  console.log(`── نتیجه: ${counts.categories} دسته‌بندی، ${counts.events} ایونت ──`);
}

main()
  .catch((err) => {
    console.error("❌ Seed failed:", err.message);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
