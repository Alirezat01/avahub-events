/** یافتن لندینگ با اسلاگ URL */
export function findTypeLanding(slug: string): EventTypeLanding | undefined {
  return EVENT_TYPE_LANDINGS.find((t) => t.slug === slug);
}

/** نوع دیتابیس → اسلاگ لندینگ (برای لینک‌دهی داخلی) */
export function dbTypeToSlug(dbType: string | null | undefined): string | null {
  if (!dbType) return null;
  const hit = EVENT_TYPE_LANDINGS.find((t) => t.db === dbType.toUpperCase());
  return hit?.slug ?? null;
}

/** نقشهٔ نوع دیتابیس → @type در اسکیمای schema.org رویداد */
const SCHEMA_EVENT_TYPE: Record<string, string> = {
  MUSIC: "MusicEvent",
  CONFERENCE: "BusinessEvent",
  SEMINAR: "EducationEvent",
  WORKSHOP: "EducationEvent",
  NETWORKING: "SocialEvent",
  EXHIBITION: "BusinessEvent",
  BRAND_ACTIVATION: "BusinessEvent",
  CEREMONY: "SocialEvent",
  GALLERY: "VisualArtsEvent",
  SPORT: "SportsEvent",
  OTHER: "Event",
};

export function schemaEventType(dbType: string | null | undefined): string | undefined {
  if (!dbType) return undefined;
  return SCHEMA_EVENT_TYPE[dbType.toUpperCase()];
}

/**
 * فاز M — خدمات مرتبط با یک رویداد برای لینک‌سازی داخلی
 * اول بر اساس نوع، اگر نوع نداشت بر اساس کیورد عنوان/خلاصه
 */
export function pickRelatedServicesForEvent(ev: {
  eventType?: string | null;
  title: string;
  summary?: string | null;
}): { slug: string; title: string }[] {
  const byType = dbTypeToSlug(ev.eventType);
  const landing = byType
    ? EVENT_TYPE_LANDINGS.find((t) => t.slug === byType)
    : undefined;
  if (landing) {
    return landing.services
      .map((slug) => {
        const s = SERVICES.find((x) => x.slug === slug);
        return s ? { slug: s.slug, title: s.title } : null;
      })
      .filter((x): x is { slug: string; title: string } => Boolean(x));
  }
  // fallback: کیوردی
  const text = `${ev.title} ${ev.summary ?? ""}`.toLowerCase();
  const hit = EVENT_TYPE_LANDINGS.find((t) =>
    t.matchKeywords.some((kw) => text.includes(kw.toLowerCase())),
  );
  if (!hit) return [];
  return hit.services
    .map((slug) => {
      const s = SERVICES.find((x) => x.slug === slug);
      return s ? { slug: s.slug, title: s.title } : null;
    })
    .filter((x): x is { slug: string; title: string } => Boolean(x));
}
